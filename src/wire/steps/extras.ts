import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { StepResult, WireContext } from "../types.js";

type ParsedUrl = {
  hostname: string;
  port: number;
  useSsl: boolean;
};

type BazarrSettings = {
  sonarr?: { ip?: string; port?: number; apikey?: string };
  radarr?: { ip?: string; port?: number; apikey?: string };
};

type TautulliIdentity = {
  pms_url?: string;
  pms_ip?: string;
  pms_port?: number;
};

const UNPACKERR_DOWNLOAD_PATHS = ["/data/torrents/tv", "/data/torrents/movies"] as const;

const EXTRA_SERVICES = ["unpackerr", "bazarr", "tautulli", "jackett"] as const;

function parseBaseUrl(url: string): ParsedUrl {
  const parsed = new URL(url);
  const defaultPort = parsed.protocol === "https:" ? 443 : 80;

  return {
    hostname: parsed.hostname,
    port: parsed.port ? Number(parsed.port) : defaultPort,
    useSsl: parsed.protocol === "https:",
  };
}

function plexUrlMatches(identity: TautulliIdentity, plexUrl: string): boolean {
  const expected = parseBaseUrl(plexUrl);
  return (
    identity.pms_ip === expected.hostname &&
    identity.pms_port === expected.port &&
    Boolean(identity.pms_url)
  );
}

function bazarrMatches(
  settings: BazarrSettings,
  sonarr: ParsedUrl,
  sonarrKey: string,
  radarr: ParsedUrl,
  radarrKey: string,
): boolean {
  return (
    settings.sonarr?.ip === sonarr.hostname &&
    settings.sonarr?.port === sonarr.port &&
    settings.sonarr?.apikey === sonarrKey &&
    settings.radarr?.ip === radarr.hostname &&
    settings.radarr?.port === radarr.port &&
    settings.radarr?.apikey === radarrKey
  );
}

async function bazarrGet<T>(url: string, apiKey: string, fetchFn: typeof fetch): Promise<T> {
  const response = await fetchFn(`${url}/api/system/settings?apikey=${encodeURIComponent(apiKey)}`);
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
  }
  return response.json() as Promise<T>;
}

async function bazarrPostForm(
  url: string,
  apiKey: string,
  data: Record<string, string>,
  fetchFn: typeof fetch,
): Promise<void> {
  const body = new URLSearchParams(data).toString();
  const response = await fetchFn(`${url}/api/system/settings?apikey=${encodeURIComponent(apiKey)}`, {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body,
  });

  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
  }
}

function buildUnpackerrConfig(
  sonarrUrl: string,
  sonarrKey: string,
  radarrUrl: string,
  radarrKey: string,
): string {
  const paths = UNPACKERR_DOWNLOAD_PATHS.map((p) => `'${p}'`).join(", ");

  return `## Generated by plex-bootstrap

[[sonarr]]
url = "${sonarrUrl}"
api_key = "${sonarrKey}"
paths = [${paths}]
protocols = "torrent,TorrentDownloadProtocol"

[[radarr]]
url = "${radarrUrl}"
api_key = "${radarrKey}"
paths = [${paths}]
protocols = "torrent,TorrentDownloadProtocol"
`;
}

async function wireUnpackerr(ctx: WireContext): Promise<StepResult> {
  const sonarrUrl = ctx.internalUrls.sonarr;
  const radarrUrl = ctx.internalUrls.radarr;
  const sonarrKey = ctx.state.apiKeys.sonarr;
  const radarrKey = ctx.state.apiKeys.radarr;

  if (!sonarrUrl || !sonarrKey || !radarrUrl || !radarrKey) {
    return {
      name: "unpackerr",
      ok: false,
      detail: "sonarr or radarr base URL or API key not configured",
      fallback: `Write ${join(ctx.config.configRoot, "unpackerr", "unpackerr.conf")} with [[sonarr]] and [[radarr]] sections`,
    };
  }

  const configPath = join(ctx.config.configRoot, "unpackerr", "unpackerr.conf");

  try {
    await mkdir(join(ctx.config.configRoot, "unpackerr"), { recursive: true });
    await writeFile(
      configPath,
      buildUnpackerrConfig(sonarrUrl, sonarrKey, radarrUrl, radarrKey),
      "utf8",
    );

    return {
      name: "unpackerr",
      ok: true,
      detail: `wrote ${configPath}`,
    };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return {
      name: "unpackerr",
      ok: false,
      detail: message,
      fallback: `Write ${configPath} manually with Sonarr/Radarr url and api_key`,
    };
  }
}

async function wireBazarr(ctx: WireContext): Promise<StepResult> {
  const bazarrUrl = ctx.baseUrls.bazarr;
  const bazarrKey = ctx.state.apiKeys.bazarr;
  const sonarrUrl = ctx.internalUrls.sonarr;
  const radarrUrl = ctx.internalUrls.radarr;
  const sonarrKey = ctx.state.apiKeys.sonarr;
  const radarrKey = ctx.state.apiKeys.radarr;

  if (!bazarrUrl || !bazarrKey) {
    return {
      name: "bazarr",
      ok: false,
      detail: "bazarr base URL or API key not configured",
      fallback: "Open Bazarr Settings and add Sonarr/Radarr hostname, port, and API keys",
    };
  }

  if (!sonarrUrl || !sonarrKey || !radarrUrl || !radarrKey) {
    return {
      name: "bazarr",
      ok: false,
      detail: "sonarr or radarr base URL or API key not configured",
      fallback: "Open Bazarr Settings and add Sonarr/Radarr hostname, port, and API keys",
    };
  }

  const fetchFn = ctx.fetchFn ?? fetch;
  const sonarr = parseBaseUrl(sonarrUrl);
  const radarr = parseBaseUrl(radarrUrl);

  try {
    const settings = await bazarrGet<BazarrSettings>(bazarrUrl, bazarrKey, fetchFn);

    if (bazarrMatches(settings, sonarr, sonarrKey, radarr, radarrKey)) {
      return {
        name: "bazarr",
        ok: true,
        detail: "sonarr and radarr already configured",
      };
    }

    await bazarrPostForm(
      bazarrUrl,
      bazarrKey,
      {
        "settings-sonarr-ip": sonarr.hostname,
        "settings-sonarr-port": String(sonarr.port),
        "settings-sonarr-apikey": sonarrKey,
        "settings-sonarr-base_url": "",
        "settings-sonarr-ssl": "false",
        "settings-general-use_sonarr": "true",
      },
      fetchFn,
    );

    await bazarrPostForm(
      bazarrUrl,
      bazarrKey,
      {
        "settings-radarr-ip": radarr.hostname,
        "settings-radarr-port": String(radarr.port),
        "settings-radarr-apikey": radarrKey,
        "settings-radarr-base_url": "",
        "settings-radarr-ssl": "false",
        "settings-general-use_radarr": "true",
      },
      fetchFn,
    );

    return {
      name: "bazarr",
      ok: true,
      detail: "sonarr and radarr configured",
    };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return {
      name: "bazarr",
      ok: false,
      detail: message,
      fallback: "Open Bazarr Settings and add Sonarr/Radarr hostname, port, and API keys",
    };
  }
}

async function tautulliGet<T>(
  tautulliUrl: string,
  apiKey: string,
  cmd: string,
  fetchFn: typeof fetch,
): Promise<T> {
  const url = `${tautulliUrl}/api/v2?apikey=${encodeURIComponent(apiKey)}&cmd=${cmd}`;
  const response = await fetchFn(url);
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
  }
  const payload = (await response.json()) as { response?: { data?: T } };
  return (payload.response?.data ?? payload) as T;
}

async function wireTautulli(ctx: WireContext): Promise<StepResult> {
  const tautulliUrl = ctx.baseUrls.tautulli;
  const tautulliKey = ctx.state.apiKeys.tautulli;
  const plexUrl = ctx.internalUrls.plex;
  const plexToken = ctx.state.apiKeys.plex;

  if (!tautulliUrl || !tautulliKey) {
    return {
      name: "tautulli",
      ok: false,
      detail: "tautulli base URL or API key not configured",
      fallback: "Open Tautulli and connect Plex at Settings → Plex Media Server",
    };
  }

  if (!plexUrl) {
    return {
      name: "tautulli",
      ok: false,
      detail: "plex base URL not configured",
      fallback: "Open Tautulli and connect Plex at Settings → Plex Media Server",
    };
  }

  const fetchFn = ctx.fetchFn ?? fetch;
  const plex = parseBaseUrl(plexUrl);

  try {
    const identity = await tautulliGet<TautulliIdentity>(
      tautulliUrl,
      tautulliKey,
      "get_server_identity",
      fetchFn,
    );

    if (plexUrlMatches(identity, plexUrl)) {
      return {
        name: "tautulli",
        ok: true,
        detail: "plex server already configured",
      };
    }

    const params = new URLSearchParams({
      pms_ip: plex.hostname,
      pms_port: String(plex.port),
      pms_ssl: plex.useSsl ? "1" : "0",
      pms_url_manual: "1",
      server_changed: "1",
      first_run: "1",
    });

    if (plexToken) {
      params.set("pms_token", plexToken);
    }

    const response = await fetchFn(`${tautulliUrl}/configUpdate`, {
      method: "POST",
      headers: { "Content-Type": "application/x-www-form-urlencoded" },
      body: params.toString(),
    });

    if (!response.ok) {
      throw new Error(`HTTP ${response.status}: ${response.statusText}`);
    }

    return {
      name: "tautulli",
      ok: true,
      detail: "plex server configured",
    };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return {
      name: "tautulli",
      ok: false,
      detail: message,
      fallback: `Open Tautulli and connect Plex at ${plexUrl}`,
    };
  }
}

function wireJackett(ctx: WireContext): StepResult {
  const jackettUrl = ctx.internalUrls.jackett ?? "http://jackett:9117";
  const apiKey = ctx.state.apiKeys.jackett ?? "YOUR_JACKETT_API_KEY";
  const parsed = parseBaseUrl(jackettUrl);
  const torznabBase = `${parsed.useSsl ? "https" : "http"}://${parsed.hostname}:${parsed.port}/api/v2/indexers`;

  return {
    name: "jackett",
    ok: true,
    detail: "add Jackett indexers manually in Sonarr/Radarr using torznab feeds",
    fallback: `${torznabBase}/{indexer}/results/torznab/api?apikey=${apiKey}`,
  };
}

const WIRERS: Record<(typeof EXTRA_SERVICES)[number], (ctx: WireContext) => Promise<StepResult> | StepResult> = {
  unpackerr: wireUnpackerr,
  bazarr: wireBazarr,
  tautulli: wireTautulli,
  jackett: wireJackett,
};

export async function wireExtras(ctx: WireContext): Promise<StepResult[]> {
  const results: StepResult[] = [];

  for (const service of EXTRA_SERVICES) {
    if (!ctx.config.services[service]) {
      continue;
    }

    results.push(await WIRERS[service](ctx));
  }

  return results;
}
